    // Shared for the whole process: the interface language must not depend on which view model
    // instance a component happens to receive.
    private static Language _current = Language.En;

    public Language Current => _current;

    public void Set(Language language) => SetLanguage(language);

    public static void SetLanguage(Language language)
    {
        if (_current == language) return;

        _current = language;
        Changed?.Invoke();
    }

    public static event Action? Changed;

    /// <summary>Forces every subscribed component to re-render with the current language.</summary>
    public static void NotifyChanged() => Changed?.Invoke();

    /// <summary>Translates a key. Unknown keys return the key itself so gaps are visible, not silent.</summary>
    public string this[string key] =>
        Current == Language.Ua && Ua.TryGetValue(key, out var ua) ? ua
        : En.TryGetValue(key, out var en) ? en
        : key;

    public string T(string key) => this[key];

    public string F(string key, params object[] args)
    {
        var template = this[key];

        try
        {
            return string.Format(template, args);
        }
        catch (FormatException)
        {
            return template;
        }
    }

    public static Language FromCode(string? code) =>
        string.Equals(code, "ua", StringComparison.OrdinalIgnoreCase) ? Language.Ua : Language.En;

    public static string ToCode(Language language) => language == Language.Ua ? "ua" : "en";

    // Static access for code that has no view model, such as the analysis engine.
    private static readonly Localization Shared = new();

    public static string S(string key) => Shared[key];

    public static string SF(string key, params object[] args) => Shared.F(key, args);
